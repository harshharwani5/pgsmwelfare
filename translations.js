// Global Translation & Switcher Logic Engine
function updateLangUI(lang) {
    const isHindi = lang === 'hi';
    
    document.querySelectorAll('.lang-btn-en').forEach(btn => {
        if (isHindi) {
            btn.classList.remove('bg-[#F36F21]', 'text-white', 'shadow-xs');
            btn.classList.add('text-gray-600', 'hover:text-gray-900');
        } else {
            btn.classList.add('bg-[#F36F21]', 'text-white', 'shadow-xs');
            btn.classList.remove('text-gray-600', 'hover:text-gray-900');
        }
    });

    document.querySelectorAll('.lang-btn-hi').forEach(btn => {
        if (isHindi) {
            btn.classList.add('bg-[#F36F21]', 'text-white', 'shadow-xs');
            btn.classList.remove('text-gray-600', 'hover:text-gray-900');
        } else {
            btn.classList.remove('bg-[#F36F21]', 'text-white', 'shadow-xs');
            btn.classList.add('text-gray-600', 'hover:text-gray-900');
        }
    });

    document.querySelectorAll('.mobile-lang-label').forEach(el => {
        el.textContent = isHindi ? 'English' : 'हिन्दी';
    });
}

function applyLanguage(lang) {
    const targetLang = (lang === 'hi') ? 'hi' : 'en';
    localStorage.setItem('pgsm_selected_lang', targetLang);
    document.documentElement.lang = targetLang;
    
    updateLangUI(targetLang);

    // Swap text for data-i18n elements
    document.querySelectorAll('[data-i18n]').forEach(el => {
        const key = el.getAttribute('data-i18n');
        if (PGSM_TRANSLATIONS[targetLang] && PGSM_TRANSLATIONS[targetLang][key]) {
            el.innerHTML = PGSM_TRANSLATIONS[targetLang][key];
        }
    });

    // Swap placeholders for data-i18n-placeholder elements
    document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
        const key = el.getAttribute('data-i18n-placeholder');
        if (PGSM_TRANSLATIONS[targetLang] && PGSM_TRANSLATIONS[targetLang][key]) {
            el.placeholder = PGSM_TRANSLATIONS[targetLang][key];
        }
    });
}

function setLanguage(lang) {
    applyLanguage(lang);
}

function toggleLanguage() {
    const current = localStorage.getItem('pgsm_selected_lang') || 'en';
    setLanguage(current === 'hi' ? 'en' : 'hi');
}

// Auto-run on DOM ready
document.addEventListener('DOMContentLoaded', () => {
    const savedLang = localStorage.getItem('pgsm_selected_lang') || 'en';
    applyLanguage(savedLang);
});

